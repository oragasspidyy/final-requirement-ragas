// Generates lib/firebase_options.dart from android/app/google-services.json.
//
// Usage (from the project folder):
//     dart run tool/make_firebase_options.dart
import 'dart:convert';
import 'dart:io';

void main() {
  final jsonFile = File('android/app/google-services.json');
  if (!jsonFile.existsSync()) {
    stderr.writeln('android/app/google-services.json not found.\n'
        'Download it from Firebase Console → Project settings → Your apps → '
        'Android app, and put it in android/app/.');
    exitCode = 1;
    return;
  }

  final data = jsonDecode(jsonFile.readAsStringSync()) as Map<String, dynamic>;
  final project = data['project_info'] as Map<String, dynamic>;
  final clients = (data['client'] as List).cast<Map<String, dynamic>>();

  // Prefer the client whose package name matches the app.
  const wantedPackage = 'com.petcarehub.petcarehub';
  Map<String, dynamic> client = clients.first;
  for (final c in clients) {
    final pkg = c['client_info']?['android_client_info']?['package_name'];
    if (pkg == wantedPackage) client = c;
  }
  final pkg = client['client_info']['android_client_info']['package_name'];
  if (pkg != wantedPackage) {
    stdout.writeln('Warning: google-services.json is for "$pkg", but the app id '
        'is "$wantedPackage". Register the Android app in Firebase with '
        '"$wantedPackage" (or change applicationId in android/app/build.gradle.kts).');
  }

  final apiKey = (client['api_key'] as List).first['current_key'];
  final appId = client['client_info']['mobilesdk_app_id'];
  final sender = project['project_number'];
  final projectId = project['project_id'];
  final bucket = project['storage_bucket'] ?? '$projectId.appspot.com';

  final out = '''
// GENERATED by tool/make_firebase_options.dart from google-services.json.
// Re-run the tool if you change Firebase projects.

import 'package:firebase_core/firebase_core.dart' show FirebaseOptions;
import 'package:flutter/foundation.dart'
    show defaultTargetPlatform, kIsWeb, TargetPlatform;

class DefaultFirebaseOptions {
  static FirebaseOptions get currentPlatform {
    if (kIsWeb) {
      throw UnsupportedError('PetCareHub is configured for Android only.');
    }
    switch (defaultTargetPlatform) {
      case TargetPlatform.android:
        return android;
      default:
        throw UnsupportedError('PetCareHub is configured for Android only.');
    }
  }

  static const FirebaseOptions android = FirebaseOptions(
    apiKey: '$apiKey',
    appId: '$appId',
    messagingSenderId: '$sender',
    projectId: '$projectId',
    storageBucket: '$bucket',
  );
}
''';
  File('lib/firebase_options.dart').writeAsStringSync(out);
  stdout.writeln('lib/firebase_options.dart created for project "$projectId".');
}
